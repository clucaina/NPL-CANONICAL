import assert from 'node:assert/strict';
import {createExplanadaLOD} from './local_mosaic_lod.mjs';
const scene={objects:[],add(o){this.objects.push(o)},remove(o){this.objects=this.objects.filter(x=>x!==o)}};
const load=async url=>({scene:{url,position:{set(x,y,z){this.coords=[x,y,z]}}}});
const cfg={scene,loader:{loadAsync:load},nearUrl:'/local/near.glb',farUrl:'/local/far.glb'};
assert.throws(()=>createExplanadaLOD({...cfg,localAnchor:{x:1,y:0,z:0},projection:x=>x}),/vertical datum/);
assert.throws(()=>createExplanadaLOD({...cfg,preview:true,localAnchor:{x:1,z:0}}),/origin/);
const viewer=createExplanadaLOD({...cfg,preview:true});
assert.equal(viewer.ready,false);
await viewer.preload();assert.equal(viewer.ready,true);
assert.equal(viewer.update(2),'physical_4cm_tesserae');assert.equal(scene.objects.length,1);
assert.equal(scene.objects[0].url,'/local/near.glb');
assert.equal(viewer.update(20),'textured_far_2_triangles');assert.equal(scene.objects.length,1);
assert.equal(scene.objects[0].url,'/local/far.glb');
assert.throws(()=>viewer.update(-1),/Invalid distance/);
viewer.dispose();assert.equal(scene.objects.length,0);
const anchored=createExplanadaLOD({...cfg,localAnchor:{x:8,y:1.2,z:2,verified:true,verticalDatumVerified:true},projection:q=>({x:q.x+100,y:q.y,z:q.z-100})});
await anchored.preload();anchored.update(5);assert.deepEqual(scene.objects[0].position.coords,[108,1.2,-98]);anchored.dispose();
console.log('PASS LOD: collision authority unchanged; preview/certified anchor guard; near/far; dispose');